#!/usr/bin/env bash
# install.sh — one-command install for the LogMem self-host bundle.
#
#   ./selfhost/install.sh [first-space]
#
# Generates selfhost/.env (600) with fresh credentials the first time,
# starts server + Redis with docker compose, waits for health, and verifies
# the admin sign-in. Idempotent: an existing .env is reused untouched.
set -euo pipefail
cd "$(dirname "$0")"

SPACE="${1:-main}"
SERVER_PORT="${SERVER_PORT:-3899}"
REDIS_PORT="${REDIS_PORT:-6399}"

fail() { echo "install: $*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || fail "docker is required (https://docs.docker.com/get-docker/)"
docker info >/dev/null 2>&1 || fail "the docker daemon is not running (start Docker Desktop / colima)"
docker compose version >/dev/null 2>&1 || fail "docker compose v2 is required"
command -v openssl >/dev/null 2>&1 || fail "openssl is required to generate credentials"
command -v curl >/dev/null 2>&1 || fail "curl is required for the health check"

case "$SPACE" in
  *[!a-z0-9-]*|"") fail "first space must be lowercase letters, digits or dashes: got '$SPACE'" ;;
esac

gen() { openssl rand -hex 32; }

if [ -f .env ]; then
  echo "reusing existing selfhost/.env"
else
  cat > .env <<EOF
# LogMem self-host credentials — generated by install.sh $(date -u +%Y-%m-%dT%H:%M:%SZ).
# This file is yours: git ignores it, keep it chmod 600, never commit it.

# First space. LOGMEM_SPACE names it, LOGMEM_SPACES allows it.
LOGMEM_SPACES=$SPACE
LOGMEM_SPACE=$SPACE
LOGMEM_VIEW_SPACES=$SPACE

# Publish loopback only (127.0.0.1). Change SERVER_PORT if it is taken.
SERVER_HOST=0.0.0.0
SERVER_PORT=$SERVER_PORT
REDIS_PORT=$REDIS_PORT

# Your own credentials, generated here, never shipped with the bundle.
LOGMEM_ADMIN_PASSWORD=$(gen)
LOGMEM_DECIDE_SECRET=$(gen)
LOGMEM_OAUTH_KEK=$(gen)
CRON_SECRET=$(gen)
REDIS_PASSWORD=$(gen)

# The bundle runs Redis over plaintext on the compose network (loopback
# published, password required). This is the designed local hatch that
# allows it. Never set it on a hosted deployment.
LOGMEM_OAUTH_ALLOW_INSECURE=1
EOF
  chmod 600 .env
  echo "wrote selfhost/.env (mode 600) with fresh credentials"
fi

echo "building and starting server + redis ..."
docker compose up -d --build

port=$(grep -E '^SERVER_PORT=' .env | tail -1 | cut -d= -f2)
admin_pw=$(grep -E '^LOGMEM_ADMIN_PASSWORD=' .env | tail -1 | cut -d= -f2-)

echo -n "waiting for health"
ok=""
for _ in $(seq 1 90); do
  if curl -sf "http://127.0.0.1:$port/api/health" >/dev/null 2>&1; then ok=1; break; fi
  echo -n "."
  sleep 1
done
echo
[ -n "$ok" ] || { docker compose logs --tail 30 server >&2; fail "server did not become healthy in 90s"; }

health=$(curl -sf "http://127.0.0.1:$port/api/health")
echo "health: $health"

login_code=$(curl -s -o /dev/null -w '%{http_code}' -X POST "http://127.0.0.1:$port/api/login" \
  -H 'Content-Type: application/json' \
  --data "{\"password\":\"$admin_pw\"}")
[ "$login_code" = "200" ] || fail "admin sign-in check returned $login_code (see docker compose logs server)"

space=$(grep -E '^LOGMEM_SPACES=' .env | tail -1 | cut -d= -f2)
cat <<SUMMARY

LogMem is up.
  URL:          http://127.0.0.1:$port
  First space:  $space
  Admin sign-in: http://127.0.0.1:$port/keys  (password in selfhost/.env, LOGMEM_ADMIN_PASSWORD)

Next steps:
  1. Open /keys, sign in with the admin password.
  2. Mint your first agent key there and put it in your MCP client config.
  3. Read selfhost/README.md for cron jobs, backups and updates.
SUMMARY
